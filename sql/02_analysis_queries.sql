-- Her dönemde kaç sektör verisi bulunmaktadýr 
SELECT 
COUNT(DISTINCT S.SECTOR_ID) 
SECTOR_DISTINCT,
P.PERIOD_LABEL PERIOD_LABEL
FROM EMPLOYMENT_EXPECTATIONS E
JOIN PERIODS P ON E.PERIOD_ID = P.PERIOD_ID
JOIN SECTORS S ON E.SECTOR_ID = S.SECTOR_ID
WHERE P.PERIOD_LABEL IN  ('2025Q1', '2025Q2', '2025Q3', '2025Q4', '2026Q1')
GROUP BY P.PERIOD_LABEL
;

