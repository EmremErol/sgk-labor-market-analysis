--2026Q1 döneminde en yüksek açýk iþ sayýsýna sahip ilk 10 sektör hangileridir
SELECT 
TOP 10
P.PERIOD_LABEL , 
S.SECTOR_NAME, 
Q.OPEN_JOB_COUNT
FROM QUARTERLY_CORE_METRICS Q
JOIN PERIODS P ON Q.PERIOD_ID = P.PERIOD_ID
JOIN SECTORS S ON Q.SECTOR_ID = S.SECTOR_ID
WHERE P.PERIOD_LABEL = '2026Q1'
ORDER BY Q.OPEN_JOB_COUNT DESC ;

