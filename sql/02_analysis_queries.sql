--2025Q1 döneminde istihdamý artýrma/koruma beklentisi en yüksek sektörler hangileridir
SELECT 
P.PERIOD_LABEL,
S.SECTOR_NAME,
E.MAINTAIN_OR_INCREASE_PCT TOP_SECTORS
FROM EMPLOYMENT_EXPECTATIONS E
JOIN PERIODS P ON E.PERIOD_ID = P.PERIOD_ID
