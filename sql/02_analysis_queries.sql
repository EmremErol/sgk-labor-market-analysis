--2025Q3 döneminde üretim/hizmet artýþ beklentisi en yüksek sektörler hangileridir?
SELECT 
P.PERIOD_LABEL,
PE.MAINTAIN_OR_INCREASE_PCT,
S.SECTOR_NAME
FROM PRODUCTION_EXPECTATIONS PE
JOIN PERIODS P ON PE.PERIOD_ID = P.PERIOD_ID
