--Ýstihdam beklentisi ile üretim beklentisi arasýndaki fark en yüksek olan sektörler hangileridir?
SELECT
S.SECTOR_NAME,
P.PERIOD_LABEL,
E.MAINTAIN_OR_INCREASE_PCT EMPLOYMENT_EXPECTATION,
PE.MAINTAIN_OR_INCREASE_PCT PRODUCTION_EXPECTATION,
ABS(E.MAINTAIN_OR_INCREASE_PCT - PE.MAINTAIN_OR_INCREASE_PCT) EXPECTATION_DIFFERENCE
FROM EMPLOYMENT_EXPECTATIONS E
JOIN PRODUCTION_EXPECTATIONS PE ON E.PERIOD_ID = PE.PERIOD_ID
AND E.SECTOR_ID = PE.SECTOR_ID
JOIN PERIODS P ON E.PERIOD_ID = P.PERIOD_ID
JOIN SECTORS S ON E.SECTOR_ID =S.SECTOR_ID
ORDER BY EXPECTATION_DIFFERENCE DESC

-- Meslek gruplarýna göre en yüksek teknik beceri, iletiþim becerisi ve problem çözme becerisi skorlarý hangileridir
SELECT 
LTRIM(RTRIM(O.OCCUPATION_GROUP)) AS OCCUPATION_GROUP,
AVG(CAST(O.TECHNICAL_SKILL AS DECIMAL(5,2)))  AVG_TECHNICAL_SKILL,
AVG(CAST(O.COMMUNICATION_SKILL AS DECIMAL(5,2)))  AVG_COMMUNICATION_SKILL,
AVG(CAST(O.PROBLEM_SOLVING_SKILL AS DECIMAL(5,2))) AVG_PROBLEM_SOLVING_SKILL
FROM OCCUPATION_SKILL_ANALYSIS O
GROUP BY LTRIM(RTRIM(O.OCCUPATION_GROUP))
ORDER BY AVG_PROBLEM_SOLVING_SKILL DESC;







